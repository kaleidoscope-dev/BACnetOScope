BACNET_PROPERTY_ID GetPropertyId(const char *propName)
{
 for (int c=0;c<BACNET_PROPERTY_COUNT;c++)
     {
      if (strcmp(propName,bacnetPropertyName[c].name) == 0)
         {
          return (BACNET_PROPERTY_ID) c;
         }
     }
 return (BACNET_PROPERTY_ID)-1;
}






